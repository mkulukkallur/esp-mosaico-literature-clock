"""Generate main/tz_table.c: IANA zone name -> POSIX TZ string.

The device learns its IANA zone (e.g. "Europe/Paris") from an IP lookup or from
the clock_timezone shared setting, but newlib's localtime() needs a POSIX rule
("CET-1CEST,M3.5.0,M10.5.0/3"). Every TZif v2+ file ends with exactly that rule
as a footer, so it is read from the IANA database packaged as Python's tzdata.

Requires:  python -m pip install tzdata
Usage:     python tools/build_tz.py
"""
from importlib import resources
from pathlib import Path

import tzdata

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "main" / "tz_table.c"


def footer(data):
    if data[:4] != b"TZif" or data[4:5] < b"2":
        return None
    tail = data.rstrip(b"\n")
    rule = tail[tail.rfind(b"\n") + 1:].decode("ascii")
    return rule or None


def main():
    names = resources.files("tzdata").joinpath("zones").read_text().split()
    rows = []
    for name in sorted(names):
        if not ("/" in name or name in ("UTC", "GMT")) or name.startswith(("Etc/", "SystemV/")):
            continue
        parts = name.split("/")
        data = resources.files("tzdata.zoneinfo").joinpath(*parts).read_bytes()
        rule = footer(data)
        if rule and "<" not in name:
            rows.append((name, rule))
    lines = [f"/* Generated by tools/build_tz.py from IANA tzdata {tzdata.IANA_VERSION}. Do not edit. */",
             '#include "tz_table.h"', "",
             "const tz_entry_t tz_table[] = {"]
    lines += [f'    {{"{n}", "{r}"}},' for n, r in rows]
    lines += ["};", f"const int tz_table_count = {len(rows)};", ""]
    OUT.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"{len(rows)} zones -> {OUT}")


if __name__ == "__main__":
    main()
